  const dir = join(ROOT, ".agents", "skills", "midnight-version-matrix");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "SKILL.md"), md);
  const json = JSON.stringify(v, null, 2) + "\n";
  writeFileSync(join(dir, "versions.json"), json);
