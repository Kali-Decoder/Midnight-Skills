export function loadErrors() {
  return JSON.parse(readFileSync(ERRORS_PATH, "utf8"));
}

export function validateErrors(data, skillIds) {
  const problems = [];
  const layers = new Set((data.layers || []).map((l) => l.id));
  (data.errors || []).forEach((e, i) => {
    const at = `errors.json #${i} (${e.match ?? "?"})`;
    for (const k of ["layer", "match", "cause", "fix"]) if (!e[k]) problems.push(`${at}: missing ${k}`);
    if (e.layer && !layers.has(e.layer)) problems.push(`${at}: unknown layer ${e.layer}`);
    if (e.skill && !skillIds.has(e.skill)) problems.push(`${at}: unknown skill id ${e.skill}`);
  });
  return problems;
}

export function buildErrorTables(data, skills) {
  const byId = new Map(skills.map((s) => [s.id, s]));
  return data.layers
    .map((layer) => {
      const rows = data.errors
        .filter((e) => e.layer === layer.id)
        .map((e) => {
          const skill = byId.get(e.skill);
          const link = skill ? `[\`${skill.id}\`](../${skill.path.replace(/^\.agents\/skills\//, "")})` : "";
          const text = e.match.includes("`") ? e.match : `\`${e.match}\``;
          const match = e.code ? `**${e.code}** ${text}` : text;
          return [match, e.cause, e.fix, link];
        });
      if (!rows.length) return null;
      return `### ${layer.title}\n\n${table(["Error", "Cause", "Fix", "Skill"], rows)}`;
    })
    .filter(Boolean)
    .join("\n\n");
}
